// Service Worker (wird beim Build erzeugt): cacht die komplette App -> offline nutzbar.
const VERSION = '__VERSION__'
const FILES = __FILES__
const CACHE = 'drehmoment-' + VERSION

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('drehmoment-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})
self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return
  // Seite: erst Netz (für Updates), sonst Cache. Assets: Cache zuerst (Dateinamen enthalten Hashes).
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then((r) => { const c = r.clone(); caches.open(CACHE).then((x) => x.put('./', c)); return r })
      .catch(() => caches.match('./', { ignoreSearch: true })))
    return
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((r) => {
    if (r.ok) { const c = r.clone(); caches.open(CACHE).then((x) => x.put(req, c)) }
    return r
  })))
})
